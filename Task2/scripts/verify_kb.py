#!/usr/bin/env python3
"""Гейт качества базы знаний knowledge_base/.

Проверяет три инварианта и завершается с кодом 1 при любом нарушении
(пригодно для CI / pre-commit):
  (а) документов >= 30;
  (б) не осталось ни одного оригинального маркера The Witcher;
  (в) тексты читаемы (достаточная длина и доля словесных символов).

Стоп-лист намеренно ШИРЕ ключей terms_map.json: ловит и косвенные маркеры
(краснолюд, Каэдвен, Аэдирн), подсказывая, чем дополнить словарь.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

KB_DIR = Path(__file__).resolve().parent.parent / "knowledge_base"
MIN_FILES = 30
MIN_CHARS = 500
MIN_WORDS = 80

# Основы маркеров (matched как \b(основа)\w*). Кириллица + латиница на случай
# непереведённых вкраплений в исходных статьях.
STOP_STEMS = [
    "ведьмак", "ведьмач", "Геральт", "Йеннифэр", "Йеннифер", "Цири", "Цирилл",
    "Трисс", "Меригольд", "Весемир", "Лютик", "Эмгыр", "Эмрейс", "Вильгефорц",
    "Эмиель", "Регис", "Роггевеен", "Ламберт", "Золтан", "Хивай", "Дийкстра", "Радовид",
    "утопец", "утопц", "леш", "стрыг", "кикимор", "накер", "грифон", "виверн",
    "доплер", "Игни", "Аард", "Квен", "Ирден", "Аксий", "мутаген",
    "Нильфгаард", "Каэр Морхен", "Новиград", "Велен", "Скеллиг", "Цинтр",
    "Темери", "Редани", "Туссент", "Венгерберг", "Риви", "Каэдвен", "Аэдирн",
    "Брокилон", "Скоятаэл", "Скоя’таэл", "Скоя'таэл", "краснолюд", "низуш",
    "Дикая Охот", "Дикой Охот",
    # вторичные персонажи и локации (добавлены по результатам частотного скана)
    "Фольтест", "Детлафф", "Эйльхарт", "Филипп", "Аваллак", "Калантэ", "Иорвет",
    "Эскел", "Мелитэле", "Хенсельт", "Фрингиль", "Ярпен", "Флотзам", "Гвинт",
    "Вызим", "Ковир", "Боклер", "Понтар", "Содден", "Танедд", "Махакам", "Блавикен",
    # точные двусловные формы (бареные «старш»/«волк»/«сфер» — общие слова)
    "Старшая Кров", "Старшей Кров", "Старшую Кров", "Старшею Кров",
    "Старшая Реч", "Старшей Реч", "Сопряжение Сфер", "Сопряжения Сфер",
    "Белый Волк", "Белого Волка", "Школа Волка", "Школы Волка",
    # латиница как защита (после tidy() её быть не должно вовсе)
    "Geralt", "witcher", "Nilfgaard", "Aen", "Seidhe", "Yennefer", "Ciri",
    "Jaskier", "Emhyr", "Zireael", "Gwynbleidd",
]
STOP_RE = re.compile(
    r"\b(" + "|".join(re.escape(s) for s in STOP_STEMS) + r")\w*",
    re.IGNORECASE | re.UNICODE,
)


def main() -> int:
    files = sorted(KB_DIR.glob("*.md")) if KB_DIR.exists() else []
    ok = True

    # (а) количество
    if len(files) < MIN_FILES:
        print(f"FAIL: {len(files)} документов (требуется >= {MIN_FILES})")
        ok = False
    else:
        print(f"OK: {len(files)} документов (>= {MIN_FILES})")

    leaks = 0
    short = 0
    for path in files:
        text = path.read_text(encoding="utf-8")

        # (б) маркеры исходной вселенной
        hits = STOP_RE.findall(text)
        if hits:
            sample = sorted({h.lower() for h in hits})[:8]
            print(f"  LEAK {path.name}: {sample}")
            leaks += len(hits)
            ok = False

        # (в) читаемость
        words = re.findall(r"\w{2,}", text, flags=re.UNICODE)
        if len(text) < MIN_CHARS or len(words) < MIN_WORDS:
            print(f"  SHORT {path.name}: {len(text)} симв., {len(words)} слов")
            short += 1
            ok = False

    print(f"\nИтог: файлов={len(files)}, утечек={leaks}, коротких={short}")
    print("РЕЗУЛЬТАТ: " + ("ЧИСТО ✓" if ok else "ЕСТЬ ПРОБЛЕМЫ ✗"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
